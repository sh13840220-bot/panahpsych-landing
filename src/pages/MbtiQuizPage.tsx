/* =========================================================================
   ۴. تابع محاسبه نمره ترجیحی و گره‌گشایی
   ========================================================================= */
function calcPreferenceScore(s1: number, s2: number, isSpecial: boolean): number {
  const diff = Math.abs(s1 - s2) * 2;
  if (isSpecial) {
    // حروف I, N, F, P
    return diff + 1;
  } else {
    // حروف E, S, T, J
    return Math.max(1, diff - 1);
  }
}

